// node scripts/gen-param-stress.mjs -> test/stress/params-<N>-parameters-<dialect>.test-d.ts (#143, CORE-6):
// statements with N parameters in WHERE (AND and OR chains), INSERT VALUES (one row and many rows),
// ON CONFLICT DO UPDATE SET, UPDATE SET and IN lists, for both
// dialects, named and positional. Each pins the result type and rejects a wrong value for the last parameter
// (the file has success and error cases, so its name says neither; the error code of each rejection is pinned through GetQueryError).
import fs from "node:fs"
import path from "node:path"

const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..")

function gen(N, dialect) {
	const range = f => Array.from({ length: N }, (_, i) => f(i))
	const cols = range(i => `, c${i} integer not null`).join("")
	const named = bad => "{ " + range(i => `p${i}: ${bad && i === N - 1 ? '"x"' : i}`).join(", ") + " }"
	const pos = bad => "[" + range(i => (bad && i === N - 1 ? '"x"' : `${i}`)).join(", ") + "]"
	// the types of the values the calls pass (the last one wrong): what GetQueryError takes as its third argument
	const namedT = bad => "{ " + range(i => `p${i}: ${bad && i === N - 1 ? "string" : "number"}`).join("; ") + " }"
	const posT = bad => "[" + range(i => (bad && i === N - 1 ? "string" : "number")).join(", ") + "]"
	const rowT = bad =>
		"[" +
		range(i => (bad && i === N - 1 ? "string" : i % 5 === 2 ? "string" : i % 5 === 3 ? "null" : "number")).join(
			", ",
		) +
		"]"
	const upsertT = "[" + Array.from({ length: N }, (_, i) => (i === N - 1 ? "string" : "number")).join(", ") + "]"
	// the last parameter is reported by its name, :p<N-1>, or by its position
	const lastNamed = `:p${N - 1}`
	const lastPos = dialect === "pg" ? `$${N}` : `?${N}` // the dialect's own spelling (positionalParamSign)
	// PostgreSQL positional: $n; SQLite positional: ?NNN (SQLT-4)
	const p = i => (dialect === "pg" ? `$${i + 1}` : `?${i + 1}`)
	const where = "select id from t where " + range(i => `c${i} = :p${i}`).join(" and ") + ";"
	const whereOr = "select id from t where " + range(i => `c${i} = ${p(i)}`).join(" or ") + ";"
	const ins = `insert into t (id, ${range(i => `c${i}`).join(", ")}) values (1, ${range(p).join(", ")});`
	const upd = "update t set " + range(i => `c${i} = :p${i}`).join(", ") + " where id = 1;"
	const inl = "select id from t where c0 in (" + range(p).join(", ") + ");"
	// N / 5 rows of (integer, integer, text, nullable integer, integer)
	const rows = Array.from({ length: N / 5 }, (_, j) => "(" + [0, 1, 2, 3, 4].map(k => p(j * 5 + k)).join(", ") + ")")
	const multi = `insert into m (id, a, s, n, b) values ${rows.join(", ")};`
	const rowValue = (i, bad) => (bad && i === N - 1 ? '"x"' : i % 5 === 2 ? '"s"' : i % 5 === 3 ? "null" : `${i}`)
	const rowValues = bad => "[" + range(i => rowValue(i, bad)).join(", ") + "]"
	// H columns: id and H - 1 more in VALUES, H assignments in DO UPDATE SET: 2 * H parameters
	const H = N / 2
	const ucols = Array.from({ length: H }, (_, i) => `, u${i} integer not null`).join("")
	const upsert =
		`insert into u (id, ${Array.from({ length: H - 1 }, (_, i) => `u${i}`).join(", ")}, u${H - 1}) values (` +
		Array.from({ length: H + 1 }, (_, i) => p(i)).join(", ") +
		") on conflict (id) do update set " +
		Array.from({ length: H - 1 }, (_, i) => `u${i} = ${p(H + 1 + i)}`).join(", ") +
		";"
	const upsertN = 2 * H
	const driver = dialect === "pg" ? "mockDriver" : "sqliteMockDriver"
	const title = dialect === "pg" ? "PostgreSQL" : "SQLite"
	return `// Integration Test: CORE-6 — ${N} parameters in one statement (${title}): every parameter gets its type; one round binds
// all probes of an AND / OR chain, VALUES rows, a SET list, DO UPDATE SET and an IN list (#143). Generated by scripts/gen-param-stress.mjs.
import { sqlMigrations, type GetQueryError } from "../../src/core/sql-database.ts"
import type { DbtyperError } from "../../src/dbtyper-error.ts"
import { expectType, toBe } from "../test-utils/type-test-utils.ts"
import { ${driver} } from "../test-utils/test-databases.ts"

const _db = sqlMigrations({ driver: ${driver} })
	.apply(
		\`create table t (id integer not null${cols}); create table m (id integer not null, a integer not null, s text not null, n integer, b integer not null); create table u (id integer not null primary key${ucols});\`,
	)
	.database()

// the SQL in constants: an error is reported on the first argument, the line after @ts-expect-error
const whereSql = \`${where}\`
const whereOrSql = \`${whereOr}\`
const insSql = \`${ins}\`
const multiSql = \`${multi}\`
const upsertSql = \`${upsert}\`
const updSql = \`${upd}\`
const inlSql = \`${inl}\`

// ✅ SUCCESS: CORE-6 WHERE with ${N} named parameters joined by AND
const _where = await _db.query(whereSql, ${named(false)})
expectType<typeof _where>(toBe<Array<{ id: number }>>())

// ❌ ERROR: CORE-6 a wrong value for the last parameter of the AND chain
expectType<GetQueryError<typeof _db, typeof whereSql, ${namedT(true)}>>(
	toBe<DbtyperError<2509, "Incompatible value type for parameter ${lastNamed}">>(),
)
// @ts-expect-error
await _db.query(whereSql, ${named(true)})

// ✅ SUCCESS: CORE-6 WHERE with ${N} positional parameters joined by OR
const _whereOr = await _db.query(whereOrSql, ${pos(false)})
expectType<typeof _whereOr>(toBe<Array<{ id: number }>>())

// ❌ ERROR: CORE-6 a wrong value for the last parameter of the OR chain
expectType<GetQueryError<typeof _db, typeof whereOrSql, ${posT(true)}>>(
	toBe<DbtyperError<2509, "Incompatible value type for parameter ${lastPos}">>(),
)
// @ts-expect-error
await _db.query(whereOrSql, ${pos(true)})

// ✅ SUCCESS: CORE-6 INSERT VALUES with ${N} positional parameters
const _ins = await _db.query(insSql, ${pos(false)})
expectType<typeof _ins>(toBe<[]>())

// ❌ ERROR: CORE-6 a wrong value for the last cell
expectType<GetQueryError<typeof _db, typeof insSql, ${posT(true)}>>(
	toBe<DbtyperError<2509, "Incompatible value type for parameter ${lastPos}">>(),
)
// @ts-expect-error
await _db.query(insSql, ${pos(true)})

// ✅ SUCCESS: CORE-6 INSERT with ${N / 5} VALUES rows, ${N} positional parameters (nullable column takes null)
await _db.query(multiSql, ${rowValues(false)})

// ❌ ERROR: CORE-6 a wrong value in the last row
expectType<GetQueryError<typeof _db, typeof multiSql, ${rowT(true)}>>(
	toBe<DbtyperError<2509, "Incompatible value type for parameter ${lastPos}">>(),
)
// @ts-expect-error
await _db.query(multiSql, ${rowValues(true)})

// ✅ SUCCESS: CORE-6 INSERT … ON CONFLICT DO UPDATE SET with ${upsertN} positional parameters
await _db.query(upsertSql, [${Array.from({ length: upsertN }, (_, i) => i).join(", ")}])

// ❌ ERROR: CORE-6 a wrong value for the last DO UPDATE SET assignment
expectType<GetQueryError<typeof _db, typeof upsertSql, ${upsertT}>>(
	toBe<DbtyperError<2509, "Incompatible value type for parameter ${lastPos}">>(),
)
// @ts-expect-error
await _db.query(upsertSql, [${Array.from({ length: upsertN }, (_, i) => (i === upsertN - 1 ? '"x"' : i)).join(", ")}])

// ✅ SUCCESS: CORE-6 UPDATE SET with ${N} named parameters
const _upd = await _db.query(updSql, ${named(false)})
expectType<typeof _upd>(toBe<[]>())

// ❌ ERROR: CORE-6 a wrong value for the last assignment
expectType<GetQueryError<typeof _db, typeof updSql, ${namedT(true)}>>(
	toBe<DbtyperError<2509, "Incompatible value type for parameter ${lastNamed}">>(),
)
// @ts-expect-error
await _db.query(updSql, ${named(true)})

// ✅ SUCCESS: CORE-6 IN list with ${N} positional parameters
const _in = await _db.query(inlSql, ${pos(false)})
expectType<typeof _in>(toBe<Array<{ id: number }>>())

// ❌ ERROR: CORE-6 a wrong value for the last list item
expectType<GetQueryError<typeof _db, typeof inlSql, ${posT(true)}>>(
	toBe<DbtyperError<2509, "Incompatible value type for parameter ${lastPos}">>(),
)
// @ts-expect-error
await _db.query(inlSql, ${pos(true)})
`
}

// 150 parameters only: the 100-parameter pair checked nothing the 150 one does not
for (const N of [150])
	for (const d of ["pg", "sqlite"]) {
		const name = `params-${N}-parameters-${d === "pg" ? "postgres" : "sqlite"}.test-d.ts`
		fs.writeFileSync(path.join(root, "test/stress", name), gen(N, d))
	}
