// Regenerates the LR tables of one dialect: `npm run gram:generate [-- <dialect>]` (default: postgres).
//   src/gram/<dialect>/gram.y --bison --xml--> gram.xml --scripts/gram/xml2ts.ts--> tables.d.ts (+ keywords.ts)
// Only GNU bison is required (flex is not used). See src/gram/README.md and DECISIONS.md (#52, #93).
import { spawnSync } from "node:child_process"
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"

const dialect = process.argv[2] ?? "postgres"
const dir = resolve(import.meta.dirname, "../src/gram", dialect)

const probe = spawnSync("bison", ["--version"], { encoding: "utf8" })
if (probe.error || probe.status !== 0) {
	console.error(
		"gram:generate needs GNU bison (>= 3.0) in PATH. Install it:\n" +
			"  Debian/Ubuntu: apt install bison\n  Arch/Manjaro: pacman -S bison\n  macOS: brew install bison (and put it before /usr/bin in PATH)",
	)
	process.exit(1)
}

function run(cmd, args) {
	const r = spawnSync(cmd, args, { cwd: dir, stdio: "inherit" })
	if (r.status !== 0) process.exit(r.status ?? 1)
}

// lemon grammars (sqlite: parse.y) are converted to gram.y first (+ fallback.json, keywords.ts)
const lemon = existsSync(resolve(dir, "parse.y"))
if (lemon) run("node", [resolve(import.meta.dirname, "gram/lemon2bison.mjs"), dir])

try {
	run("bison", [
		"--xml",
		"-Wno-deprecated",
		"-Wno-other",
		...(lemon ? ["-Wno-conflicts-rr"] : []),
		"-o",
		"gram.tab.c",
		"gram.y",
	])
	run("node", [resolve(import.meta.dirname, "gram/xml2ts.ts"), dir])
} finally {
	for (const f of ["gram.xml", "gram.tab.c", "gram.output"]) rmSync(resolve(dir, f), { force: true })
}

// keyword word -> terminal name, from `%token <keyword> ABORT_P ...` (a trailing `_P` is a C-macro workaround, not part of the word)
const y = readFileSync(resolve(dir, "gram.y"), "utf8")
const words = {}
for (const m of y.matchAll(/^%token\s+<keyword>([\s\S]*?)(?=\n\/\*|\n%)/gm)) {
	for (const t of m[1].split(/\s+/).filter(Boolean)) {
		const term = t.toLowerCase()
		words[term.replace(/_p$/, "")] = term
	}
}
const entries = Object.entries(words).sort(([a], [b]) => (a < b ? -1 : 1))
if (entries.length > 0) {
	writeFileSync(
		resolve(dir, "keywords.ts"),
		"// GENERATED by scripts/gram-generate.mjs from gram.y - do not edit.\n" +
			"/** Keyword text (lower case) -> bison terminal name. */\nexport type Keywords = {\n" +
			entries.map(([w, t]) => `\t${JSON.stringify(w)}: ${JSON.stringify(t)}`).join("\n") +
			"\n}\n",
	)
	console.error(`keywords.ts: ${entries.length} keywords`)
}
