// PGT-23 … PGT-34: PostgreSQL operators, DISTINCT ON, ON CONFLICT ON CONSTRAINT, OVERRIDING, data-modifying CTEs,
// FROM functions and the result types of the function catalog (FN-1, PGT-27 … PGT-34).
import { sqlMigrations, type GetQueryError } from "../../src/core/sql-database.ts"
import type { DbtyperError } from "../../src/dbtyper-error.ts"
import type { JsonValue } from "../../src/postgres/postgres-type-map.ts"
import { expectType, toBe } from "../test-utils/type-test-utils.ts"
import { mockDriver } from "../test-utils/test-databases.ts"

/** The row type of a query result, and whether a column is exactly `JsonValue` (a recursive type: compared by assignability). */
type Row<T> = T extends readonly (infer R)[] ? R : never
type IsJson<T> = [T] extends [JsonValue] ? ([JsonValue] extends [T] ? true : false) : false

const db = sqlMigrations({ driver: mockDriver })
	.apply(`create schema public;`)
	.apply(
		`create table t (
			id integer primary key, name text not null, nick text, age integer, big bigint not null, n numeric,
			r real not null, d double precision, ok boolean not null, at timestamptz not null, ts timestamp,
			dt date not null, data jsonb, js json not null, tags text[] not null, nums integer[], sm smallint not null
		);`,
	)
	.apply(
		`create table u (
			id integer primary key, code text not null, constraint u_code unique (code),
			g integer generated always as identity, h integer generated by default as identity
		);`,
	)
	.database()

// PGT-23
const _ops = await db.query(
	`select name similar to 'a%' as a, name ~ 'a' as b, nick ~* 'a' as c, name !~ 'a' as d, name !~* 'a' as e, name not similar to 'a' as f from t`,
)
expectType<typeof _ops>(toBe<{ a: boolean; b: boolean; c: boolean | null; d: boolean; e: boolean; f: boolean }[]>())
const _distinct = await db.query(`select distinct on (name, age) name, age from t order by name, age limit all`)
expectType<typeof _distinct>(toBe<{ name: string; age: number | null }[]>())
const _limitAll = await db.query(`select name from t limit all offset 1`)
expectType<typeof _limitAll>(toBe<{ name: string }[]>())
const badDistinctOn = `select distinct on (ghost) name from t` as const
// @ts-expect-error
await db.query(badDistinctOn)
expectType<GetQueryError<typeof db, typeof badDistinctOn>>(
	toBe<DbtyperError<2300, "Unknown column ghost in DISTINCT ON">>(),
)

// PGT-24
const _json = await db.query(
	`select data->>'k' as k, data->'k' as j, js#>'{a,b}' as p, data#>>'{a}' as q, js->>'x' as x from t`,
)
expectType<Omit<Row<typeof _json>, "j" | "p">>(toBe<{ k: string | null; q: string | null; x: string | null }>())
expectType<IsJson<Row<typeof _json>["j"] | Row<typeof _json>["p"]>>(toBe<true>())
const _jsonBool = await db.query(
	`select data @> '{}' as c, data <@ '{}' as d, data ? 'k' as e, data ?| array['a'] as f, data ?& array['a'] as g, js::jsonb @> '{}' as h from t`,
)
expectType<typeof _jsonBool>(
	toBe<
		{ c: boolean | null; d: boolean | null; e: boolean | null; f: boolean | null; g: boolean | null; h: boolean }[]
	>(),
)
await db.query(`select name from t where data->>'k' = 'x' and data ? 'z'`)

// PGT-25
await db.query(`insert into u (id, code) values (1, 'a') on conflict on constraint u_code do nothing`)
