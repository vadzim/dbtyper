// Integration Test: ALTER TYPE - Missing EXISTS after IF
import { sqlMigrations, type GetApplyError } from "../../../src/core/sql-database.ts"
import { mockDriver } from "../../test-utils/test-databases.ts"
import { expectType, toBe } from "../../test-utils/type-test-utils.ts"
import type { DbtyperError } from "../../../src/dbtyper-error.ts"

const migrations = sqlMigrations({ driver: mockDriver }).apply(`create type status as enum ('active');`)

// ❌ ERROR: Missing EXISTS after IF in ALTER TYPE
const query = `alter type if status add value 'inactive';` as const

// @ts-expect-error
migrations.apply(query)

type ReturnedError = GetApplyError<typeof migrations, typeof query>

expectType<ReturnedError>(toBe<DbtyperError<4000, "Expected `exists` after `IF` in ALTER TYPE">>())
