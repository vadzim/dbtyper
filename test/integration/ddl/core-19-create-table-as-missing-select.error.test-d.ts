// Integration Test: CORE-19 CREATE TABLE ... AS needs a SELECT
import { sqlMigrations, type GetQueryError, type GetApplyError } from "../../../src/core/sql-database.ts"
import { mockDriver } from "../../test-utils/test-databases.ts"
import { expectType, toBe } from "../../test-utils/type-test-utils.ts"
import type { DbtyperError } from "../../../src/dbtyper-error.ts"

const migrations = sqlMigrations({ driver: mockDriver }).apply(`create schema public;`)

// ❌ ERROR: CORE-19 nothing to select
const query = `create table t as values (1);` as const

// @ts-expect-error
migrations.apply(query)

type ReturnedError = GetApplyError<typeof migrations, typeof query>

expectType<ReturnedError>(toBe<DbtyperError<1511, "Expected SELECT or WITH after AS in CREATE TABLE">>())
