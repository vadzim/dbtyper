// Integration Test: INSERT - unknown column in ON CONFLICT
import { sqlMigrations, type GetQueryError } from "../../../src/core/sql-database.ts"
import { mockDriver } from "../../test-utils/test-databases.ts"
import { expectType, toBe } from "../../test-utils/type-test-utils.ts"
import type { DbtyperError } from "../../../src/dbtyper-error.ts"

const db = sqlMigrations({ driver: mockDriver }).apply(`create table users (id integer, name text);`).database()

// ❌ ERROR: Unknown column in ON CONFLICT
const query = `insert into users (id, name) values (1, 'test') on conflict (ghost_column) do nothing;` as const

// @ts-expect-error
await db.query(query)

type ReturnedError = GetQueryError<typeof db, typeof query>

expectType<ReturnedError>(toBe<DbtyperError<2300, "Unknown column ghost_column in ON CONFLICT">>())
